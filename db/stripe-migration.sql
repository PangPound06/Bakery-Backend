-- ════════════════════════════════════════════════════════════════════
-- Stripe payment + cancel/refund schema
--
-- รันได้ซ้ำกี่ครั้งก็ได้ (IF NOT EXISTS ทุกคำสั่ง) ไม่ลบหรือแก้ข้อมูลเดิม
--
--   localhost : psql -U postgres -d db_bakery -f db/stripe-migration.sql
--   Supabase  : Dashboard → SQL Editor → วางทั้งไฟล์ → Run
-- ════════════════════════════════════════════════════════════════════

BEGIN;

-- ─── tb_orders ───────────────────────────────────────────────────────
-- PaymentIntent ที่ผูกกับ order — webhook ใช้หา order กลับ
ALTER TABLE public.tb_orders ADD COLUMN IF NOT EXISTS stripe_payment_intent_id varchar(255);
-- บิลหน้าร้าน: alacarte / buffet (แทนการค้นคำว่า "Buffet" ใน note)
ALTER TABLE public.tb_orders ADD COLUMN IF NOT EXISTS dine_type varchar(20);
ALTER TABLE public.tb_orders ADD COLUMN IF NOT EXISTS buffet_pax integer;
ALTER TABLE public.tb_orders ADD COLUMN IF NOT EXISTS buffet_price_per_person double precision;

CREATE INDEX IF NOT EXISTS idx_orders_stripe_pi ON public.tb_orders (stripe_payment_intent_id);
CREATE INDEX IF NOT EXISTS idx_orders_email_payment_status ON public.tb_orders (email, payment_status);

-- ─── tb_order_items ──────────────────────────────────────────────────
-- จำนวน "ชิ้น" ที่ยกเลิก/คืนเงินไปแล้ว
ALTER TABLE public.tb_order_items ADD COLUMN IF NOT EXISTS cancelled_qty integer NOT NULL DEFAULT 0;

-- ─── tb_dinein_orders ────────────────────────────────────────────────
-- บิลรวมใน tb_orders ที่ออเดอร์โต๊ะนี้ถูกรวมเข้าไป
ALTER TABLE public.tb_dinein_orders ADD COLUMN IF NOT EXISTS bill_order_id bigint;
CREATE INDEX IF NOT EXISTS idx_dinein_orders_bill ON public.tb_dinein_orders (bill_order_id);

-- ─── tb_stripe_events — กัน webhook ซ้ำ ──────────────────────────────
CREATE TABLE IF NOT EXISTS public.tb_stripe_events (
    event_id    varchar(255) PRIMARY KEY,
    event_type  varchar(100) NOT NULL,
    received_at timestamp    NOT NULL DEFAULT now()
);

-- ─── tb_cancel_requests — คำขอยกเลิกของลูกค้า / แอดมิน ───────────────
CREATE TABLE IF NOT EXISTS public.tb_cancel_requests (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id         bigint        NOT NULL,
    email            varchar(255)  NOT NULL,
    scope            varchar(20)   NOT NULL,              -- full | partial
    reason_code      varchar(50),
    reason_note      text,
    estimated_refund numeric(12, 2) NOT NULL DEFAULT 0,
    status           varchar(20)   NOT NULL DEFAULT 'pending', -- pending | approved | rejected
    decided_by       varchar(255),
    decided_at       timestamp,
    decision_note    text,
    created_at       timestamp     NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_cancel_requests_order  ON public.tb_cancel_requests (order_id);
CREATE INDEX IF NOT EXISTS idx_cancel_requests_email  ON public.tb_cancel_requests (email);
CREATE INDEX IF NOT EXISTS idx_cancel_requests_status ON public.tb_cancel_requests (status);

-- ─── tb_cancel_request_items — รายการที่ขอยกเลิก ─────────────────────
CREATE TABLE IF NOT EXISTS public.tb_cancel_request_items (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id    bigint         NOT NULL REFERENCES public.tb_cancel_requests (id) ON DELETE CASCADE,
    order_item_id bigint         NOT NULL,
    quantity      integer        NOT NULL,                -- หน่วย "ชิ้น" เหมือน tb_order_items
    line_amount   numeric(12, 2) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_cancel_request_items_request ON public.tb_cancel_request_items (request_id);

-- ─── tb_refunds — ประวัติการคืนเงินผ่าน Stripe ────────────────────────
CREATE TABLE IF NOT EXISTS public.tb_refunds (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id          bigint         NOT NULL,
    cancel_request_id bigint,
    stripe_refund_id  varchar(255)   NOT NULL,
    amount            numeric(12, 2) NOT NULL,
    fee_deducted      numeric(12, 2) NOT NULL DEFAULT 0,
    refund_mode       varchar(20)    NOT NULL,            -- fee_deducted | full | manual
    reason            text,
    created_by        varchar(255),
    created_at        timestamp      NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_refunds_order ON public.tb_refunds (order_id);

COMMIT;
